import math

a = 1  # integer
b = 1.1  # float
c = 1 + 2j  # a + bi mathematical complex numbers

# Arithmetic Operators
print(10 + 3)
print(10 - 3)
print(10 * 3)
print(10 / 3)  # floating point quotient
print(10 // 3)  # integer point quotient
print(10 % 3)  # modulus (reminder)
print(10 ** 3)  # exponent

# increment/decrement operators
x = 10
x = x + 3
x += 3
print(x)

x = x - 3
x -= 3
print(x)


# number functions
print(round(2.9))
print(abs(-2.9))

# math module functions
print(math.ceil(2.2))
print(math.floor(2.2))
